_BOX = {"boxstyle": "round,pad=0.35", "linewidth": 1.3}


def _canvas(width: float = 10.0, height: float = 4.0, xlim=(0, 10), ylim=(0, 4)):
    fig, ax = plt.subplots(figsize=(width, height))
    ax.set_xlim(*xlim)
    ax.set_ylim(*ylim)
    ax.axis("off")
    ax.grid(False)
    return fig, ax


def _box(ax, x, y, w, h, text, color="#ffffff", edge="#333333", fontsize=9, weight="normal"):
    ax.add_patch(
        FancyBboxPatch((x, y), w, h, facecolor=color, edgecolor=edge, **_BOX)
    )
    ax.text(
        x + w / 2, y + h / 2, text, ha="center", va="center",
        fontsize=fontsize, fontweight=weight, wrap=True,
    )


def _arrow(ax, start, end, color="#333333", style="-|>", lw=1.4, ls="-", rad=0.0):
    ax.add_patch(
        FancyArrowPatch(
            start, end, arrowstyle=style, mutation_scale=13, linewidth=lw,
            color=color, linestyle=ls, connectionstyle=f"arc3,rad={rad}",
            shrinkA=2, shrinkB=2,
        )
    )


