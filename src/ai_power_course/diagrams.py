    ax.text(
        0.6, 0.15,
        "Each gate is a sigmoid in [0,1] multiplying a signal. Because $c_t$ is *added* to rather "
        "than\nrepeatedly multiplied, a gradient can travel hundreds of steps without vanishing.",
        fontsize=9.5,
    )
    ax.set_title("LSTM: gates around an additive memory", fontsize=11, fontweight="bold")
    return fig


