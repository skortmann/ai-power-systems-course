def neuron_and_network() -> plt.Figure:
    """A single neuron next to the network it stacks into."""
    fig, axes = plt.subplots(1, 2, figsize=(11, 3.8))
    for ax in axes:
        ax.axis("off")
        ax.grid(False)

    ax = axes[0]
    ax.set_xlim(0, 10)
    ax.set_ylim(0, 6)
    for i, label in enumerate(["x1", "x2", "x3"]):
        y = 4.5 - i * 1.5
        ax.add_patch(Circle((1.2, y), 0.42, facecolor="#f2f2f2", edgecolor="#333"))
        ax.text(1.2, y, label, ha="center", va="center", fontsize=9)
        _arrow(ax, (1.7, y), (4.3, 3.0))
        ax.text(2.9, (y + 3.0) / 2 + 0.22, f"w{i + 1}", fontsize=8.5, color=COLORS["transformer"])
    ax.add_patch(Circle((4.9, 3.0), 0.62, facecolor=COLORS["mlp"], edgecolor="#333"))
    ax.text(4.9, 3.0, r"$\Sigma$", ha="center", va="center", fontsize=13)
    _arrow(ax, (5.55, 3.0), (6.8, 3.0))
    _box(ax, 6.8, 2.35, 1.5, 1.3, "activation\n$\\sigma$", color=COLORS["accent"])
    _arrow(ax, (8.3, 3.0), (9.4, 3.0))
    ax.text(9.6, 3.0, "y", fontsize=10, va="center")
    ax.text(4.9, 1.1, r"$y=\sigma\!\left(\sum_i w_i x_i + b\right)$", ha="center", fontsize=11)
    ax.set_title("One neuron", fontsize=10, fontweight="bold")

    ax = axes[1]
    ax.set_xlim(0, 10)
    ax.set_ylim(0, 6)
    layers = [(1.3, 4, "input"), (4.0, 5, "hidden"), (6.7, 5, "hidden"), (9.0, 1, "output")]
    positions = []
    for x, count, _ in layers:
        ys = np.linspace(1.0, 5.0, count) if count > 1 else [3.0]
        positions.append([(x, y) for y in ys])
    for left, right in zip(positions[:-1], positions[1:], strict=True):
        for x0, y0 in left:
            for x1, y1 in right:
                ax.plot([x0, x1], [y0, y1], color="#cccccc", lw=0.5, zorder=1)
    colours = ["#f2f2f2", COLORS["mlp"], COLORS["mlp"], COLORS["tree"]]
    for (x, _count, name), points, colour in zip(layers, positions, colours, strict=True):
        for px, py in points:
            ax.add_patch(Circle((px, py), 0.28, facecolor=colour, edgecolor="#333", zorder=2))
        ax.text(x, 0.35, name, ha="center", fontsize=8.5)
    ax.set_title("Stacked into a multi-layer perceptron", fontsize=10, fontweight="bold")
    fig.suptitle(
        "Stage B: the model learns its own features", fontsize=11, fontweight="bold", y=1.0
    )
    fig.tight_layout()
    return fig


def backpropagation() -> plt.Figure:
    """Forward pass, loss, and the backward pass that assigns credit."""
    fig, ax = _canvas(11, 3.6)
    nodes = [("x", "#f2f2f2"), ("h = W1 x", COLORS["mlp"]), ("a = relu(h)", COLORS["mlp"]),
             ("y = W2 a", COLORS["tree"]), ("L = (y - t)^2", COLORS["transformer"])]
    width, gap = 1.7, 0.5
    for i, (label, color) in enumerate(nodes):
        x = 0.4 + i * (width + gap)
        _box(ax, x, 2.1, width, 0.95, label, color=color, fontsize=9)
        if i < len(nodes) - 1:
            _arrow(ax, (x + width, 2.58), (x + width + gap, 2.58))
    ax.text(0.4, 3.35, "forward pass: compute the prediction and the loss", fontsize=9.5)

    for i in range(len(nodes) - 1, 0, -1):
        x = 0.4 + i * (width + gap)
        _arrow(
            ax, (x, 1.75), (x - gap, 1.75), color=COLORS["transformer"], ls="--", rad=0.0
        )
    ax.text(
        0.4, 1.1,
        "backward pass: the chain rule propagates dL/d(.) right to left, so every weight "
        "learns\nhow much it contributed to the error. Backpropagation is bookkeeping, not magic.",
        fontsize=9.5, color=COLORS["transformer"],
    )
    ax.set_title("Backpropagation = the chain rule, applied efficiently", fontsize=11,
                 fontweight="bold")
    return fig


def rnn_unrolled() -> plt.Figure:
    """The same cell applied at every time step, with a hidden state carried on."""
    fig, ax = _canvas(11, 3.6)
    steps = 5
    width, gap = 1.35, 0.6
    for t in range(steps):
        x = 0.5 + t * (width + gap)
        _box(ax, x, 1.7, width, 1.0, "RNN\ncell", color=COLORS["rnn"], fontsize=9)
        _arrow(ax, (x + width / 2, 1.0), (x + width / 2, 1.65))
        ax.text(x + width / 2, 0.75, f"$x_{{t-{steps - 1 - t}}}$", ha="center", fontsize=9)
        if t < steps - 1:
            _arrow(ax, (x + width, 2.2), (x + width + gap, 2.2))
            ax.text(x + width + gap / 2, 2.4, "$h$", ha="center", fontsize=8.5)
    x_last = 0.5 + (steps - 1) * (width + gap)
    _arrow(ax, (x_last + width / 2, 2.75), (x_last + width / 2, 3.4))
    ax.text(x_last + width / 2, 3.6, "forecast", ha="center", fontsize=9)
    ax.text(
        0.5, 0.2,
        "The same weights are reused at every step, so the model handles any sequence length —\n"
        "but information must survive the whole chain, and gradients shrink with every hop.",
        fontsize=9.5,
    )
    ax.set_title("A recurrent network, unrolled in time", fontsize=11, fontweight="bold")
    return fig


def lstm_cell() -> plt.Figure:
    """Why gates: an additive cell-state highway past the multiplications."""
    fig, ax = _canvas(10, 4.2)
    _box(ax, 0.6, 0.6, 8.8, 2.9, "", color="#fbfbfb", edge="#999999")
    ax.plot([0.9, 9.1], [3.0, 3.0], color=COLORS["transformer"], lw=2.6)
    ax.text(5.0, 3.25, "cell state $c_t$ — an additive path through time", ha="center",
            fontsize=9.5, color=COLORS["transformer"])
    gates = [
        (1.5, "forget\n$f_t$", "what to drop"),
        (3.6, "input\n$i_t$", "what to write"),
        (5.7, "candidate\n$\\tilde{c}_t$", "what is new"),
        (7.8, "output\n$o_t$", "what to expose"),
    ]
    for x, label, caption in gates:
        _box(ax, x - 0.55, 1.5, 1.2, 0.95, label, color=COLORS["rnn"], fontsize=8.5)
        _arrow(ax, (x + 0.05, 2.5), (x + 0.05, 2.95))
