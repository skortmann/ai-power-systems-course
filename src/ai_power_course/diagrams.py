def self_supervised_masking() -> plt.Figure:
    """Masked prediction on a load profile — the objective, without labels."""
    rng = np.random.default_rng(7)
    hours = np.arange(24)
    profile = 50 + 9 * np.sin(2 * np.pi * (hours - 4) / 24) + 5 * np.sin(4 * np.pi * hours / 24)
    profile += rng.normal(0, 0.7, 24)
    masked = np.zeros(24, dtype=bool)
    masked[8:12] = True
    masked[18] = True

    fig, axes = plt.subplots(1, 3, figsize=(11.5, 3.0), sharey=True)
    axes[0].plot(hours, profile, color=COLORS["truth"], marker="o", ms=3)
    axes[0].set_title("1. an unlabelled day", fontsize=10)
    visible = profile.copy()
    visible[masked] = np.nan
    axes[1].plot(hours, visible, color=COLORS["truth"], marker="o", ms=3)
    for h in hours[masked]:
        axes[1].axvspan(h - 0.5, h + 0.5, color=COLORS["transformer"], alpha=0.22)
    axes[1].set_title("2. hide part of it", fontsize=10)
    axes[2].plot(hours, visible, color=COLORS["truth"], marker="o", ms=3, label="visible")
    axes[2].plot(hours[masked], profile[masked] + rng.normal(0, 0.8, masked.sum()), "x",
                 color=COLORS["foundation"], ms=8, mew=2, label="reconstructed")
    axes[2].set_title("3. predict it from the rest", fontsize=10)
    axes[2].legend(fontsize=8)
    for ax in axes:
        ax.set_xlabel("hour")
        ax.grid(alpha=0.25)
    axes[0].set_ylabel("load [MW]")
    fig.suptitle(
        "Self-supervised learning: the label is the data itself", fontsize=11, fontweight="bold"
    )
    fig.tight_layout()
    return fig


