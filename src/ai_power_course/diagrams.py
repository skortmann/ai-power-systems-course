def multi_grid_transfer() -> plt.Figure:
    """Pretrain across grids, transfer to an unseen one."""
    fig, ax = _canvas(11.5, 4.4, xlim=(0, 11.5), ylim=(0, 4.4))
    rng = np.random.default_rng(3)
    for i, (name, n_nodes) in enumerate([("grid A\n9 bus", 9), ("grid B\n30 bus", 14),
                                         ("grid C\n39 bus", 11)]):
        cx = 1.2 + i * 2.0
        points = rng.normal(0, 0.32, size=(n_nodes, 2)) + [cx, 3.4]
        for a in range(n_nodes - 1):
            ax.plot(points[a : a + 2, 0], points[a : a + 2, 1], color="#999", lw=0.7, zorder=1)
        ax.scatter(points[:, 0], points[:, 1], s=16, color=COLORS["mlp"], zorder=2)
        ax.text(cx, 2.45, name, ha="center", fontsize=8.5)
        _arrow(ax, (cx, 2.3), (6.4, 1.75), rad=0.08)
    _box(ax, 6.4, 1.2, 2.4, 1.1, "ONE encoder\n(shared weights)", color=COLORS["foundation"],
         fontsize=9, weight="bold")
    _arrow(ax, (8.9, 1.75), (9.6, 1.75), lw=2.0)
    points = rng.normal(0, 0.38, size=(18, 2)) + [10.4, 3.2]
    for a in range(17):
        ax.plot(points[a : a + 2, 0], points[a : a + 2, 1], color="#999", lw=0.7, zorder=1)
    ax.scatter(points[:, 0], points[:, 1], s=16, color=COLORS["transformer"], zorder=2)
    ax.text(10.4, 2.3, "unseen grid\n(held out)", ha="center", fontsize=8.5,
            color=COLORS["transformer"])
    ax.text(
        0.3, 0.4,
        "The parameters live in the message and update functions, which are shared by every bus "
        "and every branch.\nNothing in the model has a fixed bus count — that is what makes "
        "transfer to a different topology possible at all.",
        fontsize=9,
    )
    ax.set_title("Multi-grid pretraining and transfer", fontsize=11, fontweight="bold")
    return fig


def ai_timeline() -> plt.Figure:
    """The milestones the course walks through.

    Two panels, not one, because a single linear axis makes everything after
    2015 illegible — and that illegibility is itself the point: the field did
    in the last decade what it had previously done in five.

    Dates are the year of first public release (arXiv preprint where one
    exists), not journal publication. Several are genuinely contested — the
    perceptron, backpropagation and attention all have earlier partial
    antecedents — so read this as a teaching aid, not as priority claims.
    """
    early = [
        (1957, "Perceptron\n(Rosenblatt)"),
        (1986, "Backprop popularised\n(Rumelhart et al.)"),
        (1997, "LSTM\n(Hochreiter & Schmidhuber)"),
        (1998, "LeNet-5\n(LeCun et al.)"),
        (2006, "Deep learning\nresurgence"),
    ]
    modern = [
        (2012, "AlexNet"),
        (2013, "Word2Vec"),
        (2014, "Seq2seq; attention\n(Bahdanau)"),
        (2017, "Transformer"),
        (2018, "BERT / GPT"),
        (2020, "GPT-3; scaling laws"),
        (2021, "'Foundation model'\ncoined; CLIP"),
        (2022, "InstructGPT;\nchat models"),
        (2023, "Open-model wave;\nSAM; DINOv2"),
        (2024, "Time-series &\nscience FMs"),
        (2025, "Domain-specific FMs\n(WindFM, ...)"),
        (2026, "Grid foundation\nmodels"),
    ]

    fig, axes = plt.subplots(2, 1, figsize=(12.5, 6.2))
    panels = [
        (axes[0], early, 1950, 2011, "1950 - 2010:  the long build-up", COLORS["rnn"]),
        (axes[1], modern, 2011, 2027, "2011 - 2026:  the acceleration", COLORS["foundation"]),
    ]
    for ax, events, x0, x1, title, colour in panels:
        ax.axhline(0, color="#333333", lw=1.5)
        for i, (year, label) in enumerate(events):
            side = 1 if i % 2 == 0 else -1
            ax.plot([year, year], [0, 0.30 * side], color=colour, lw=1.2)
            ax.plot(year, 0, "o", ms=5, color=colour)
            ax.text(
                year, 0.38 * side, f"{year}\n{label}", ha="center",
                va="bottom" if side > 0 else "top", fontsize=8.0,
            )
        ax.set_xlim(x0, x1)
        ax.set_ylim(-1.5, 1.5)
        ax.set_yticks([])
        ax.spines[["left", "right", "top"]].set_visible(False)
        ax.grid(axis="x", alpha=0.2)
        ax.set_title(title, fontsize=10, fontweight="bold", loc="left")
    fig.suptitle(
        "Milestones on the way from machine learning to foundation models",
        fontsize=11.5, fontweight="bold",
    )
    fig.tight_layout()
    return fig
